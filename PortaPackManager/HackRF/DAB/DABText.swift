import Foundation

/// Prüfsummen und Zeichensätze von DAB.
enum DABCRC {
    /// CRC-16-CCITT (x¹⁶ + x¹² + x⁵ + 1), Start 0xFFFF, Ergebnis invertiert –
    /// für FIBs, AUs und PAD-Datengruppen.
    static func ccitt<C: Collection>(_ bytes: C) -> UInt16 where C.Element == UInt8 {
        ~crc(bytes, polynomial: 0x1021, initial: 0xFFFF)
    }

    /// Firecode des DAB+-Superframes (Polynom 0x782F, Start 0, nicht invertiert).
    static func fire<C: Collection>(_ bytes: C) -> UInt16 where C.Element == UInt8 {
        crc(bytes, polynomial: 0x782F, initial: 0)
    }

    private static func crc<C: Collection>(_ bytes: C, polynomial: UInt16, initial: UInt16) -> UInt16 where C.Element == UInt8 {
        var crc = initial
        for byte in bytes {
            crc ^= UInt16(byte) << 8
            for _ in 0..<8 {
                crc = crc & 0x8000 != 0 ? (crc << 1) ^ polynomial : crc << 1
            }
        }
        return crc
    }
}

