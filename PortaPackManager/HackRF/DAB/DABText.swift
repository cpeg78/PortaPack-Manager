    /// Dekodiert einen Text: 0 = EBU Latin, 4 = ISO 8859-1, 6 = UCS-2, 15 = UTF-8.
    static func decode<C: Collection>(_ bytes: C, charset: Int) -> String where C.Element == UInt8 {
        let raw = Array(bytes)
        let text: String
        switch charset {
        case 15: text = String(decoding: raw, as: UTF8.self)
        case 6:
            let units = stride(from: 0, to: raw.count - 1, by: 2).map { UInt16(raw[$0]) << 8 | UInt16(raw[$0 + 1]) }
            text = String(decoding: units, as: UTF16.self)
        case 4: text = String(raw.map { Character(Unicode.Scalar($0)) })
        default:
            text = String(String.UnicodeScalarView(raw.compactMap { Unicode.Scalar(ebuLatin[Int($0)]) }))
        }
        return text.trimmingCharacters(in: .whitespacesAndNewlines.union(.controlCharacters))
    }
