        var register = [UInt8](repeating: 1, count: 9)
        var out = [UInt8](repeating: 0, count: count)
        for i in 0..<count {
            let bit = register[8] ^ register[4]
            for j in stride(from: 8, to: 0, by: -1) { register[j] = register[j - 1] }
            register[0] = bit
            out[i] = bit
        }
        return out
    }

