/// Kenngrößen von DAB Übertragungsmodus I (ETSI EN 300 401, Tabelle 38),
/// gerechnet in Abtastwerten bei 2,048 MS/s.
enum DABMode {
    static let sampleRate = 2_048_000
    /// Länge des Nutzteils eines Symbols (T_u) = FFT-Größe.
    static let fftSize = 2048
    /// Schutzintervall (T_g).
    static let guardLength = 504
    /// Symbol mit Schutzintervall (T_s).
    static let symbolLength = 2552
    /// Nullsymbol (T_null).
    static let nullLength = 2656
    /// OFDM-Symbole je Rahmen ohne Nullsymbol (L): PRS, 3 FIC, 72 MSC.
    static let symbolsPerFrame = 76
    /// Genutzte Träger (K), ±768 ohne den mittleren.
    static let carriers = 1536
    /// Rahmenlänge (T_F) = 96 ms.
    static let frameLength = 196_608
    /// Bits je Datensymbol (2 Bit je Träger).
    static let bitsPerSymbol = 3072
    static let ficSymbols = 3
    static let mscSymbols = 72
    /// Ein Rahmen trägt 4 Common Interleaved Frames zu je 24 ms.
    static let cifsPerFrame = 4
    /// Kapazitätseinheit (CU) = 64 Bit; ein CIF hat 864 CUs.
    static let capacityUnitBits = 64
    static let capacityUnitsPerCIF = 864
    static let cifBits = 55_296
    /// Trägerabstand in Hz.
    static let carrierSpacing = 1000.0
}

/// Ein DAB-Kanal im Band III.
struct DABChannel: Identifiable, Hashable, Sendable, Codable {
    let name: String
    /// Mittenfrequenz in Hz.
    let frequency: UInt64
    var id: String { name }

    var megahertz: Double { Double(frequency) / 1_000_000 }

    /// Band III, Kanäle 5A–13F (EN 50248).
    static let bandIII: [DABChannel] = [
        ("5A", 174_928), ("5B", 176_640), ("5C", 178_352), ("5D", 180_064),
        ("6A", 181_936), ("6B", 183_648), ("6C", 185_360), ("6D", 187_072),
        ("7A", 188_928), ("7B", 190_640), ("7C", 192_352), ("7D", 194_064),
        ("8A", 195_936), ("8B", 197_648), ("8C", 199_360), ("8D", 201_072),
        ("9A", 202_928), ("9B", 204_640), ("9C", 206_352), ("9D", 208_064),
        ("10A", 209_936), ("10B", 211_648), ("10C", 213_360), ("10D", 215_072),
        ("11A", 216_928), ("11B", 218_640), ("11C", 220_352), ("11D", 222_064),
        ("12A", 223_936), ("12B", 225_648), ("12C", 227_360), ("12D", 229_072),
        ("13A", 230_784), ("13B", 232_496), ("13C", 234_208), ("13D", 235_776),
        ("13E", 237_488), ("13F", 239_200),
    ].map { DABChannel(name: $0.0, frequency: UInt64($0.1) * 1000) }

    static func named(_ name: String) -> DABChannel? {
        bandIII.first { $0.name == name }
    }
}

