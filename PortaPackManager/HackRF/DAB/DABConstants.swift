    /// Phasenreferenz je FFT-Bin (Länge 2048; ungenutzte Bins 0).
    static let prsReference: (re: [Float], im: [Float]) = {
        var re = [Float](repeating: 0, count: DABMode.fftSize)
        var im = [Float](repeating: 0, count: DABMode.fftSize)
        for k in -768...768 where k != 0 {
            let bin = (k + DABMode.fftSize) % DABMode.fftSize
            switch prsQuarterTurns(k) {
            case 0: re[bin] = 1
            case 1: im[bin] = 1
            case 2: re[bin] = -1
            default: im[bin] = -1
            }
        }
        return (re, im)
    }()

